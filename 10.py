print("Введите 2 не нулевых числа.")
a = int(input())
if a == 0:
    print("Введите не нулевое число.")
    exit()
b = int(input())
if b == 0:
    print("Введите не нулевое число.")
    exit()
c = (a * a) + (b * b)
v = (a * a) - (b * b)
n = (a * a) * (b * b)
m = (a * a) / (b * b)
print(f"Сумма, разность, произведение и частное их квадратов:", c, v, n, m)
